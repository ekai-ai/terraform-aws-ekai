sed -i "s/ACCOUNT_ID/${ACCOUNT_ID}/g" "${POLICY_DIR}/infra.json"
sed -i "s/ACCOUNT_ID/${ACCOUNT_ID}/g; s/ENV_NAME/${ENV}/g" "${POLICY_DIR}/cicd.json"

# "Already exists" alone isn't enough to skip -- this script's own embedded
# policy documents change over time (e.g. a missing action discovered later),
# and an existing customer's live policy needs those fixes to actually reach
# their account. Compare documents and publish a new version when they drift.
for pair in "${INFRA_POLICY_NAME}:${POLICY_DIR}/infra.json" "${CICD_POLICY_NAME}:${POLICY_DIR}/cicd.json"; do
  PNAME="${pair%%:*}"; PFILE="${pair#*:}"
  PARN="arn:aws:iam::${ACCOUNT_ID}:policy/${PNAME}"
  if aws iam get-policy --policy-arn "${PARN}" >/dev/null 2>&1; then
    CURRENT_VERSION=$(aws iam get-policy --policy-arn "${PARN}" --query 'Policy.DefaultVersionId' --output text)
    CURRENT_DOC=$(aws iam get-policy-version --policy-arn "${PARN}" --version-id "${CURRENT_VERSION}" --query 'PolicyVersion.Document' --output json | jq -S .)
    NEW_DOC=$(jq -S . "${PFILE}")
    if [[ "${CURRENT_DOC}" == "${NEW_DOC}" ]]; then
      echo "==> Policy ${PNAME} already up to date (${CURRENT_VERSION}) — reusing."
    else
      echo "==> Policy ${PNAME} exists but its permissions have changed — publishing a new version."
      VERSION_COUNT=$(aws iam list-policy-versions --policy-arn "${PARN}" --query 'length(Versions)' --output text)
      if [[ "${VERSION_COUNT}" -ge 5 ]]; then
        OLDEST_NON_DEFAULT=$(aws iam list-policy-versions --policy-arn "${PARN}" --query 'Versions[?IsDefaultVersion==`false`]|sort_by(@, &CreateDate)[0].VersionId' --output text)
        echo "    (at IAM's 5-version limit — deleting oldest non-default version ${OLDEST_NON_DEFAULT})"
        aws iam delete-policy-version --policy-arn "${PARN}" --version-id "${OLDEST_NON_DEFAULT}"
      fi
      aws iam create-policy-version --policy-arn "${PARN}" --policy-document "file://${PFILE}" --set-as-default >/dev/null
      echo "✓ ${PNAME} updated."
    fi
  else
    echo "==> Creating policy ${PNAME}..."
    aws iam create-policy --policy-name "${PNAME}" --policy-document "file://${PFILE}" >/dev/null
  fi
done

if aws iam get-user --user-name "${USER_NAME}" >/dev/null 2>&1; then
  echo "==> IAM user ${USER_NAME} already exists — reusing."
else
  echo "==> Creating IAM user ${USER_NAME}..."
  aws iam create-user --user-name "${USER_NAME}" >/dev/null
fi

aws iam attach-user-policy --user-name "${USER_NAME}" --policy-arn "${INFRA_ARN}"
aws iam attach-user-policy --user-name "${USER_NAME}" --policy-arn "${CICD_ARN}"
echo "==> Policies attached to ${USER_NAME}."

# AWS never returns an existing key's secret again, and this script truncates
# SECRETS_FILE on every run — so a previously created key's secret is always
# unrecoverable by the time this runs a second time. Reusing "whatever's
# ambient" instead of this exact user is not a safe fallback: EKS clusters
# created with authentication_mode = CONFIG_MAP (this codebase's default,
# see the cluster submodule's kubernetes_config_map_v1_data.aws_auth) grant
# automatic access ONLY to the IAM identity that created the cluster. Any
# other identity — including the operator's own default AWS credentials —
# gets "Unauthorized" on every Kubernetes/Helm resource in this same apply.
# So: always mint a fresh key for USER_NAME and deactivate old ones, rather
# than ever falling back to ambient credentials.
mapfile -t EXISTING_KEYS < <(aws iam list-access-keys --user-name "${USER_NAME}" --query 'sort_by(AccessKeyMetadata, &CreateDate)[].AccessKeyId' --output text | tr '\t' '\n')
if [[ ${#EXISTING_KEYS[@]} -ge 2 ]]; then
  echo "==> ${USER_NAME} already has 2 access keys (AWS's max) — deleting the oldest (${EXISTING_KEYS[0]}) to make room."
  aws iam delete-access-key --user-name "${USER_NAME}" --access-key-id "${EXISTING_KEYS[0]}"
  EXISTING_KEYS=("${EXISTING_KEYS[@]:1}")
fi

echo "==> Creating a fresh access key for ${USER_NAME}..."
AK_JSON=$(aws iam create-access-key --user-name "${USER_NAME}")
TF_AWS_ACCESS_KEY_ID=$(echo "${AK_JSON}" | jq -r .AccessKey.AccessKeyId)
TF_AWS_SECRET_ACCESS_KEY=$(echo "${AK_JSON}" | jq -r .AccessKey.SecretAccessKey)
{
  echo "AWS_ACCESS_KEY_ID=${TF_AWS_ACCESS_KEY_ID}"
  echo "AWS_SECRET_ACCESS_KEY=${TF_AWS_SECRET_ACCESS_KEY}"
} >> "${SECRETS_FILE}"
echo "==> Access key created: ${TF_AWS_ACCESS_KEY_ID} (secret saved to ${SECRETS_FILE})"

for OLD_KEY in "${EXISTING_KEYS[@]}"; do
  echo "==> Deactivating previous access key ${OLD_KEY} (its secret is no longer known to this script)."
  aws iam update-access-key --user-name "${USER_NAME}" --access-key-id "${OLD_KEY}" --status Inactive
done
echo

# ── Step 2 — Passwords ────────────────────────────────────────────────────────
echo "──── Step 2/4: Passwords ───────────────────────────────────────────"
if [[ "${CICD_PROVIDER}" == "none" ]]; then
  echo "==> cicd_provider = \"none\" (self-service) — the platform submodule generates"
  echo "    its own ArgoCD admin password, the cluster submodule its own RDS"
  echo "    credentials. Skipping."
  echo "    Retrieve the ArgoCD password after apply: it's also in the customer"
  echo "    secret's ARGOCD_PASSWORD key, or run (from examples/self-deploy/root)"
  echo "    terraform output -raw argocd_admin_password"
else
  echo "Leave any prompt blank to auto-generate a strong random value."
  read -rsp "ArgoCD admin password (blank = auto-generate): " ARGOCD_PW; echo
  [[ -z "${ARGOCD_PW}" ]] && ARGOCD_PW=$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 24)
  ARGOCD_HASH=$(htpasswd -nbBC 12 "" "${ARGOCD_PW}" | tr -d ':\n' | sed 's/$2y/$2a/')

  read -rsp "Backend DB password (blank = auto-generate): " BACKEND_DB_PW; echo
  [[ -z "${BACKEND_DB_PW}" ]] && BACKEND_DB_PW=$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 24)

  read -rsp "Semantics DB password (blank = auto-generate): " SEMANTICS_DB_PW; echo
  [[ -z "${SEMANTICS_DB_PW}" ]] && SEMANTICS_DB_PW=$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 24)

  {
    echo "argocd_admin_password_plain=${ARGOCD_PW}"
    echo "backend_db_password=${BACKEND_DB_PW}"
    echo "semantics_db_password=${SEMANTICS_DB_PW}"
  } >> "${SECRETS_FILE}"

  echo "==> Updating argocd_admin_password_hashed in ${TFVARS}..."
  sed -i "s|^argocd_admin_password_hashed.*|argocd_admin_password_hashed = \"${ARGOCD_HASH}\"|" "${TFVARS}"
fi
echo

# ── Step 3 — Secrets Manager ──────────────────────────────────────────────────
echo "──── Step 3/4: Secrets Manager ─────────────────────────────────────"
if [[ "${CICD_PROVIDER}" == "none" ]]; then
  echo "==> cicd_provider = \"none\" (self-service) — no master secret, no"
  echo "    per-service secrets. The cluster/platform/cicd submodules generate and"
  echo "    create everything they need directly. Skipping this step entirely."
else
  MASTER_SECRET="${ENV}-ekai-db-credentials"

  if aws secretsmanager describe-secret --secret-id "${MASTER_SECRET}" --region "${REGION}" >/dev/null 2>&1; then
    echo "==> ${MASTER_SECRET} already exists — not overwriting (it may already be in use)."
    echo "    Update it manually if needed: aws secretsmanager put-secret-value --secret-id ${MASTER_SECRET} ..."
  else
    echo "==> Creating ${MASTER_SECRET}..."
    aws secretsmanager create-secret \
      --name "${MASTER_SECRET}" \
      --region "${REGION}" \
      --secret-string "$(jq -n \
        --arg bu "ekai_backend" --arg bp "${BACKEND_DB_PW}" --arg bn "ekai_backend" \
        --arg su "ekai_semantics" --arg sp "${SEMANTICS_DB_PW}" --arg sn "ekai_semantics" \
        --arg ap "${ARGOCD_PW}" \
        '{backend_db_username:$bu, backend_db_password:$bp, backend_db_name:$bn,
          semantics_db_username:$su, semantics_db_password:$sp, semantics_db_name:$sn,
          argocd_admin_password: $ap,
          github_token:"EKAI-PROVIDES-THIS", github_username:"EKAI-PROVIDES-THIS", github_email:"EKAI-PROVIDES-THIS"}')" \
      >/dev/null
    echo "✓ ${MASTER_SECRET} created. github_token/username/email are placeholders —"
    echo "  fill in the real GitHub PAT before running terraform apply (needs repo, admin:repo_hook, workflow scopes)."
  fi

  for SVC in ekai-backend ekai-erd ekai-semantics ekai-profile; do
    SNAME="${ENV}-${SVC}"
    if aws secretsmanager describe-secret --secret-id "${SNAME}" --region "${REGION}" >/dev/null 2>&1; then
      echo "==> ${SNAME} already exists — skipping."
    else
      aws secretsmanager create-secret --name "${SNAME}" --region "${REGION}" --secret-string "{}" >/dev/null
      echo "✓ ${SNAME} created (empty — Ekai populates DATABASE_URL etc. after infra deploy)."
    fi
  done
fi
echo

# ── Step 4 — Deploy (optional) ────────────────────────────────────────────────
echo "──── Step 4/4: Deploy infrastructure ───────────────────────────────"
echo "Everything above is prep — no cloud infrastructure has been created yet."
echo "This next step creates real AWS resources (VPC, EKS, RDS, ...) and costs money."
echo
read -rp "Run the Terraform deploy now (2 applies — bootstrap+cluster+platform, then cicd)? [y/N] " CONFIRM
if [[ ! "${CONFIRM}" =~ ^[Yy]$ ]]; then
  echo
  echo "Skipped. When you're ready, deploy locally:"
  echo "  ${SCRIPT_DIR}/init-state-backend.sh ${ENV}"
  echo "  cd ${REPO_ROOT}/examples/self-deploy/root"
  echo "  terraform init -backend-config=../../../env/backend-${ENV}.tfbackend"
  echo "  terraform apply -var-file=../../../env/${ENV}.tfvars"
  echo "  cd ../cicd"
  echo "  terraform init -backend-config=../../../env/backend-${ENV}-cicd.tfbackend"
  echo "  terraform apply -var-file=../../../env/${ENV}.tfvars"
  echo "(use the AWS_ACCESS_KEY_ID/AWS_SECRET_ACCESS_KEY values in ${SECRETS_FILE} if a new key was created above)"
  echo
  echo "Generated secrets are saved at: ${SECRETS_FILE}"
  echo "Copy them into your password manager, then delete the file."
  exit 0
fi

echo "==> Waiting for the new IAM key to propagate..."
