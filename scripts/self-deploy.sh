#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────────
# self-deploy.sh  —  AWS self-deployment, made easy
#
# Usage:  ./scripts/self-deploy.sh <ENV>
#   ENV   environment name — must have a matching env/<ENV>.tfvars
#         (e.g. dev, qa, staging, test, client1)
#
# What it does, in plain terms:
#   1. Creates the scoped IAM user Terraform needs (not admin/root access)
#   2. Generates strong passwords for you (or accepts your own)
#   3. Creates the AWS Secrets Manager secrets Terraform reads at deploy time
#   4. Updates env/<ENV>.tfvars with the new ArgoCD password hash
#   5. Saves everything it generated to a local file (chmod 600) so nothing
#      is lost — you copy that into your password manager, then delete it
#   6. Optionally runs the actual Terraform deploy — 2 applies (repo root,
#      then cicd/; down from 4 separate layers in the original design, but
#      not all the way to 1 — see cicd/main.tf's file header for why),
#      after one clear confirmation, since that step creates real cloud
#      resources and costs money
#
# You do NOT need to know Terraform, IAM policies, or bcrypt to run this.
# Everything it creates is idempotent — safe to re-run if it fails partway.
#
# Requires: aws cli, htpasswd, openssl, jq, dig, terraform. The identity aws cli
#           is configured with only needs permission to manage one IAM user
#           and two IAM policies -- see ../PERMISSIONS.md for the exact
#           policy, not full account admin.
# ──────────────────────────────────────────────────────────────────────────────
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
